  // Lookup helper functions
  function getProfileById(id) {
    if (id === undefined || id === null) return null;
    const cleanId = String(id).trim();
    const numId = parseInt(cleanId, 10);
    return ALL_PROFILES.find(p => p.id === numId) ||
           ALL_PROFILES.find(p => String(p.id) === cleanId) ||
           null;
  }

  function getProfileByName(name) {
    if (!name || typeof name !== 'string') return null;
    const query = name.trim().toLowerCase();
    return ALL_PROFILES.find(p => p.name.toLowerCase() === query) ||
           ALL_PROFILES.find(p => p.name.toLowerCase().includes(query)) ||
           null;
  }

  function getProfileCountByReligion() {
    const counts = { hindu: 0, muslim: 0, sikh: 0, christian: 0, total: ALL_PROFILES.length };
    ALL_PROFILES.forEach(p => {
      const rel = (p.religion || '').toLowerCase();
      if (counts[rel] !== undefined) counts[rel]++;
    });
    return counts;
  }

  // Expose on global Matchly namespace
  window.Matchly.profiles = ALL_PROFILES;
  window.Matchly.getProfileById = getProfileById;
  window.Matchly.getProfileByName = getProfileByName;
  window.Matchly.getProfileCountByReligion = getProfileCountByReligion;
